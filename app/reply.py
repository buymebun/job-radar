_DASH = re.compile(r"\s*[—–]\s*")


def _clean(text: str) -> str:
    """Убираем длинные тире и маркеры списков, если модель всё же их вставила."""
    lines = []
    for line in text.splitlines():
        line = re.sub(r"^\s*[•\-*]\s+", "", line)
        lines.append(_DASH.sub(", ", line).replace("**", ""))
    return re.sub(r"\n{3,}", "\n\n", "\n".join(lines)).strip()


async def draft(vid: int) -> str:
    v = db.one("SELECT * FROM vacancies WHERE id=?", (vid,))
    src = db.one("""SELECT r.text FROM vacancy_sources s JOIN raw_posts r ON r.id=s.raw_post_id
                    WHERE s.vacancy_id=? ORDER BY r.date LIMIT 1""", (vid,))
    user = (f"Вакансия: {v['title']} ({v['job_type'] or 'тип не указан'}, {v['format']}, {v['vertical']})\n"
            f"Суть: {v['summary']}\n\nИсходный текст:\n{(src['text'] if src else '')[:3000]}")
    data, _model = await llm.complete_json(SYSTEM.format(profile=profile_text()), user)
    text = _clean(str(data.get("text") or ""))
    db.x("UPDATE vacancies SET draft=? WHERE id=?", (text, vid))
    return text
